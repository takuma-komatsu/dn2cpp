# Uninstall-on-every-exit-path: a device must not accumulate gate installs,
# and the keep-screen-on override below must never outlive the run.
device_fail() {
    echo "FAIL: $1" >&2
    [ -f "$DEVLOG" ] && tail -40 "$DEVLOG" >&2
    adb -s "$SERIAL" shell svc power stayon false >/dev/null 2>&1 || true
    adb -s "$SERIAL" shell am force-stop "$PKG" >/dev/null 2>&1 || true
    adb -s "$SERIAL" uninstall "$PKG" >/dev/null 2>&1 || true
    exit 1
}

adb -s "$SERIAL" install -r "$APK" >"$OUT/install.log" 2>&1 \
    || { cat "$OUT/install.log" >&2; device_fail "adb install failed"; }
adb -s "$SERIAL" logcat -c >/dev/null 2>&1 || true

# A sleeping/locked device never resumes the activity, so no frame ever runs
# and no marker ever prints (observed: the task opened with isSleeping=true and
# sat paused — and a device that re-dozed mid-boot paused the game between the
# engine banner and the drop-in init). Keep the screen on for the whole run
# (restored in every exit path), then wake and dismiss with settle pauses —
# best effort, an unsecured lockscreen dismisses.
adb -s "$SERIAL" shell svc power stayon true >/dev/null 2>&1 || true
device_wake() {
    adb -s "$SERIAL" shell input keyevent KEYCODE_WAKEUP >/dev/null 2>&1 || true
    sleep 1
    adb -s "$SERIAL" shell wm dismiss-keyguard >/dev/null 2>&1 || true
    sleep 1
}
device_wake
# The exported LAUNCHER is the activity-alias (GodotApp itself is not
# exported on the stock template — starting it from the shell is a
# SecurityException).
adb -s "$SERIAL" shell am start -n "$PKG/com.godot.game.GodotAppLauncher" >/dev/null 2>&1 \
    || device_fail "am start failed"

# The AutoVerify sequence quits itself after ~3 s of playback polling; poll
# logcat for its terminal marker, bounded well past that. If the game's BOOT
# marker has not appeared after ~20 s, the activity most likely never resumed
# (a re-locked screen) — wake and relaunch once before giving up.
found_done=""
relaunched=""
for _i in $(seq 1 60); do
    adb -s "$SERIAL" logcat -d > "$DEVLOG" 2>/dev/null || true
    if grep -q "CRI_E2E_DONE" "$DEVLOG"; then found_done=1; break; fi
    if [ "$_i" -eq 10 ] && [ -z "$relaunched" ] && ! grep -q "CRI_E2E_BOOT" "$DEVLOG"; then
        relaunched=1
        device_wake
        adb -s "$SERIAL" shell am start -n "$PKG/com.godot.game.GodotAppLauncher" >/dev/null 2>&1 || true
    fi
    sleep 2
done
[ -n "$found_done" ] || device_fail "timed out waiting for CRI_E2E_DONE in logcat"

# Positive markers: engine boot, the drop-in's C# alive (BOOT can only come
# from the transpiled game), CRI initialized (a real version string), the cue
# reaching Playing — the stand-in for audibility: a Playing voice means the
# output stream is being rendered into — and the summary line with the
# playing=True / errors=False verdict baked in.
for marker in \
    "Godot Engine v" \
    "CRI_E2E_BOOT" \
    "CRI_E2E_VERSION CRI Atom" \
    "CRI_E2E_PLAY_STARTED" \
    "CRI_E2E_PLAYING" \
    "CRI_E2E_RESULT playing=True" \
    "CRI_E2E_DONE"; do
    grep -qF "$marker" "$DEVLOG" || device_fail "missing logcat marker: $marker"
done
grep -q "errors=False" <<<"$(grep -F "CRI_E2E_RESULT" "$DEVLOG" || true)" \
    || device_fail "the CRI error callback fired during the run (CRI_E2E_RESULT errors!=False)"
# Negative markers: no CRI error callback, no managed exception, no mono-module
# init failure, no native crash in the game process.
for bad in "CRI_E2E_ERROR" "CRI_E2E_EXCEPTION" \
    "Unable to find the .NET assemblies directory" \
    "GodotPlugins initialization failed"; do
    grep -qF "$bad" "$DEVLOG" && device_fail "logcat contains \"$bad\""
done
if grep -qi "godot\|criware" <<<"$(grep -E "Fatal signal|FATAL EXCEPTION" "$DEVLOG" || true)"; then
    device_fail "the game process crashed (Fatal signal / FATAL EXCEPTION in logcat)"
fi

# Observations for the record (not asserts): the audio stack lines the OS
# printed for the run, and anything JNI-flavored the CRI JNI shim logged —
# libcri_jni_shared.so gets no JNI_OnLoad from a dlopen'd chain, and whether
# that matters is exactly what this run observes.
echo "-- audio stack lines:"
grep -E "AAudio|AudioTrack|OpenSL|audio_hw" "$DEVLOG" | tail -8 || true
echo "-- CRI/JNI lines:"
grep -iE "criware|cri_|JNI_OnLoad" "$DEVLOG" | grep -v "CRI_E2E_" | tail -8 || true

adb -s "$SERIAL" shell svc power stayon false >/dev/null 2>&1 || true
adb -s "$SERIAL" shell am force-stop "$PKG" >/dev/null 2>&1 || true
adb -s "$SERIAL" uninstall "$PKG" >/dev/null 2>&1 \
    || echo "warning: adb uninstall $PKG failed (already removed?)"
echo "device run OK: booted, CRI initialized, cue reached Playing, no errors"

assert_editor_toolchain_current "$FORK_GODOTSHARP"
gate_cache_commit
echo "OK"
