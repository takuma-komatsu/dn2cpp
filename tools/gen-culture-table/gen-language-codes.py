#!/usr/bin/env python3
"""Extract ISO language pairs from ICU uloc.cpp's parallel language tables."""

import argparse
import re
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("uloc", type=Path)
parser.add_argument("icu_version", help="version of the ICU tree that uloc came from")
args = parser.parse_args()
source = re.sub(r"/\*.*?\*/|//[^\n]*", "", args.uloc.read_text(), flags=re.S)


def table(name):
    match = re.search(r"constexpr const char\* " + name + r"\[\] = \{(.*?)\};", source, re.S)
    if match is None:
        raise ValueError("missing ICU table: " + name)
    return [item.group(1) for item in re.finditer(r'"([^\"]+)"|\bnullptr\b', match.group(1))]


languages = table("LANGUAGES")
three_letters = table("LANGUAGES_3")
if len(languages) != len(three_letters):
    raise ValueError("ICU language tables have different lengths")
pairs = {}
for source_code, target_code in zip(three_letters, languages):
    if source_code is not None and len(target_code) == 2:
        pairs.setdefault(source_code, target_code)
print("// Generated by tools/gen-culture-table/gen-language-codes.py from ICU " + args.icu_version)
print("// icu4c/source/common/uloc.cpp LANGUAGES / LANGUAGES_3. First matches win.")
print("static const Dn2CppCultureNameMapping kCultureIsoLanguageCodes[] = {")
entries = [f'{{ u"{key}", u"{value}" }}' for key, value in sorted(pairs.items())]
for index in range(0, len(entries), 4):
    print("    " + ", ".join(entries[index:index + 4]) + ",")
print("};")
