#!/usr/bin/env python3
"""Regenerate DnBrotli's binary tables from the vendored Brotli C initializers."""

import argparse
import hashlib
from pathlib import Path
import re
import struct


ROOT = Path(__file__).resolve().parent
VENDOR = ROOT.parents[1] / "third_party" / "brotli" / "c"


def numbers(initializer):
    initializer = re.sub(r"/\*.*?\*/", "", initializer, flags=re.S)
    if re.sub(r"0x[0-9a-fA-F]+|[0-9]+|[\s,{}]", "", initializer):
        raise ValueError("Expected a literal numeric initializer")
    return [int(value, 0) for value in re.findall(r"0x[0-9a-fA-F]+|[0-9]+", initializer)]


def array(source, name):
    text = (VENDOR / source).read_text()
    match = re.search(r"\b" + name + r"\s*\[[^\]]*\]\s*=\s*\{(.*?)\};", text, re.S)
    if match is None:
        raise ValueError(f"Missing {name} in {source}")
    return numbers(match[1])


def dictionary_field(name):
    text = (VENDOR / "common/dictionary.c").read_text()
    match = re.search(r"/\* " + name + r" \*/\s*\{(.*?)\}", text, re.S)
    if match is None:
        raise ValueError(f"Missing dictionary field {name}")
    return numbers(match[1])


def pack(values, layout):
    width = len(layout)
    if len(values) % width:
        raise ValueError(f"Incomplete {layout} record")
    return b"".join(struct.pack("<" + layout, *values[i:i + width])
                    for i in range(0, len(values), width))


def byte_property(name, data):
    rows = [", ".join(f"0x{value:02X}" for value in data[i:i + 32])
            for i in range(0, len(data), 32)]
    body = ",\n".join("        " + row for row in rows)
    print(f"{name}: {len(data)} bytes, sha256 {hashlib.sha256(data).hexdigest()}")
    return f"    internal static ReadOnlySpan<byte> {name} =>\n    [\n{body}\n    ];\n"


def uint_field(name, values):
    rows = [", ".join(str(value) for value in values[i:i + 8])
            for i in range(0, len(values), 8)]
    body = ",\n".join("        " + row for row in rows)
    return f"    internal static readonly uint[] {name} =\n    {{\n{body}\n    }};\n"


def generated_file(namespace, name, sources, body, version):
    provenance = "\n".join(f"// Source: third_party/brotli/c/{source}." for source in sources)
    return (f"// <auto-generated />\n"
            f"// Generated by internal/DnBrotli/gen_tables.py from brotli v{version}.\n"
            f"{provenance}\n"
            f"// Do not edit by hand.\n\n"
            f"namespace DnBrotli.{namespace};\n\n"
            f"internal static class {name}\n{{\n{body}}}\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated files differ")
    args = parser.parse_args()
    version_text = (VENDOR / "common/version.h").read_text()
    version = ".".join(re.search(r"#define BROTLI_VERSION_" + part + r"\s+(\d+)",
                                version_text)[1] for part in ("MAJOR", "MINOR", "PATCH"))
    dictionary = byte_property("Data", pack(array("common/dictionary_inc.h", "kBrotliDictionaryData"), "B"))
    dictionary += "\n" + byte_property("SizeBitsByLength", bytes(dictionary_field("size_bits_by_length")))
    dictionary += "\n" + uint_field("OffsetsByLength", dictionary_field("offsets_by_length"))
    hash_tables = "    // kStaticDictionaryHashWords: uint16, little-endian.\n"
    hash_tables += byte_property("HashWordsLE", pack(array("enc/dictionary_hash_inc.h", "kStaticDictionaryHashWords"), "H"))
    hash_tables += "\n" + byte_property("HashLengths", pack(array("enc/dictionary_hash_inc.h", "kStaticDictionaryHashLengths"), "B"))
    lookup = "    // kStaticDictionaryBuckets: uint16, little-endian.\n"
    lookup += byte_property("BucketsLE", pack(array("enc/static_dict_lut_inc.h", "kStaticDictionaryBuckets"), "H"))
    lookup += "\n    // kStaticDictionaryWords: DictWord { byte len; byte transform; ushort idx; }.\n"
    lookup += byte_property("WordsLE", pack(array("enc/static_dict_lut_inc.h", "kStaticDictionaryWords"), "BBH"))
    files = [
        ("Common", "DictionaryData", ["common/dictionary.c", "common/dictionary_inc.h"], dictionary),
        ("Enc", "DictionaryHash", ["enc/dictionary_hash_inc.h"], hash_tables),
        ("Enc", "StaticDictLut", ["enc/static_dict_lut_inc.h"], lookup),
    ]
    mismatches = []
    for namespace, name, sources, body in files:
        path = ROOT / "src" / "DnBrotli" / namespace / (name + ".g.cs")
        content = generated_file(namespace, name, sources, body, version)
        if args.check:
            if not path.exists() or path.read_text() != content:
                mismatches.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(content)
    if mismatches:
        parser.exit(1, "Generated tables differ: " + ", ".join(mismatches) + "\n")


if __name__ == "__main__":
    main()
